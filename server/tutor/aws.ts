export interface TutorLesson {
  title: string;
  rule: string;
  reasoning: string;
  trap: string;
  recall: string;
  contrast: string;
  scenario: string;
  options: [string, string, string, string];
  explanation: string;
  check: string;
}
export interface TutorChapter {
  title: string;
  pageStart: number;
  pageEnd?: number;
  description: string;
  lessons: TutorLesson[];
}

function lesson(
  title: string,
  recall: string,
  rule: string,
  trap: string,
  scenario: string,
  options: TutorLesson['options'],
  reasoning: string,
): TutorLesson {
  return {
    title,
    recall,
    rule,
    trap,
    scenario,
    options,
    reasoning,
    explanation: reasoning,
    contrast: `What failure mode or trade-off must you avoid when designing ${title.toLowerCase()}?`,
    check: `A design review concerns ${title.toLowerCase()}. Which principle correctly guides the decision?`,
  };
}

